'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('resources/js/juego.js','utf8');
const start=source.indexOf('const RANDOM_RESET_COOLDOWN_MS=1000;');
const end=source.indexOf('function resetRandomSeedByKey(){',start);
assert(start>=0&&end>start,'No se encontró el control de cooldown de R');
let now=10_000;
const context={Date:{now:()=>now}};
vm.createContext(context);
vm.runInContext(source.slice(start,end),context);
assert.equal(context.canStartRandomReset(),true,'La primera pulsación debe permitirse');
now+=999;
assert.equal(context.canStartRandomReset(),false,'Debe bloquearse antes de cumplir 1 segundo');
now+=1;
assert.equal(context.canStartRandomReset(),true,'Debe permitirse al cumplir exactamente 1 segundo');
now+=1000;
assert.equal(context.canStartRandomReset(),true,'Debe seguir permitiéndose tras otro segundo');
console.log('COOLDOWN R OK: una aceptación como máximo por cada intervalo de 1000 ms.');
